#######################################################################################################################################
#                                                   load packages
#######################################################################################################################################
cd(@__DIR__)
using Pkg
Pkg.activate("../..")
using Revise
using ACTRModels
using ACTRMCEModels
using LaTeXStrings
using Plots
#######################################################################################################################################
#                                                   setup model
#######################################################################################################################################
# specify model parameters: partial matching, noise, mismatch penalty, activation noise
Θ = (mmp = true, noise = true, δ = 0.8, s = 0.20, blc = 0.0, τ = -100)
# base level constant activation for each chunk: F∧B, F̄∧B, F∧B̄, F̄∧B̄
blcs = [-1.0, -1.5, 0, 0.5]
model = ACTRJointProb(; blcs, Θ...)
#######################################################################################################################################
#                                                   run example
#######################################################################################################################################
pyplot()

x_labels = [
    L"\mathbf{c}_{\mathrm{FB}}",
    L"\mathbf{c}_{\mathrm{\bar{F}B}}",
    L"\mathbf{c}_{\mathrm{F\bar{B}}}",
    L"\mathbf{c}_{\mathrm{\bar{F}\bar{B}}}"
]

config = (
    axis = font(6),
    titlefontsize = 7,
    ylims = (0, 1),
    label = false,
    grid = false,
    yticks = [0, 0.50, 1],
    color = RGB(139/255, 187/255, 199/255),
    dpi = 300
)
#######################################################################################################################################
#                                                   empty retrieval request
#######################################################################################################################################
request = ()
target = get_chunks(model.actr; request...)
p, _ = retrieval_probs(model.actr; request...)
plot_none = bar(x_labels, p[1:4]; title = L"∅", config...)
#######################################################################################################################################
#                                                   bank teller
#######################################################################################################################################
request = (B = true,)
target = get_chunks(model.actr; request...)
p, _ = retrieval_probs(model.actr; request...)
plot_B = bar(x_labels, p[1:4]; title = L"\mathbf{r}_B", config...)
#######################################################################################################################################
#                                                   feminist and bank teller
#######################################################################################################################################
request = (B = true, F = true)
target = get_chunks(model.actr; request...)
p, _ = retrieval_probs(model.actr; request...)
plot_FB = bar(x_labels, p[1:4]; title = L"\mathbf{r}_{\mathrm{FB}}", config...)
#######################################################################################################################################
#                                                   feminist
#######################################################################################################################################
request = (F = true,)
target = get_chunks(model.actr; request...)
p, _ = retrieval_probs(model.actr; request...)
plot_F = bar(x_labels, p[1:4]; title = L"\mathbf{r}_{F}", config...)
#######################################################################################################################################
#                                                   combine plots
#######################################################################################################################################
plot(plot_none, plot_B, plot_FB, plot_F, layout = (4, 1), size = (245, 250))
savefig("partial_matching_joint_distributions.eps")
