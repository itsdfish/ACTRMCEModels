#######################################################################################################################################
#                                                           load packages
#######################################################################################################################################
cd(@__DIR__)
using Pkg
Pkg.activate("../..")
using Revise
using ACTRModels
using ACTRMCEModels
using Distributions
using ACTRMCEModels: simulate_trial
#######################################################################################################################################
#                                                           setup simulation
#######################################################################################################################################
Θ = (mmp = true, noise = true, s = 0.20, blc = 0.0)
bl = Normal(0, 0.50)
max_sub_events = 5
n_sim = 100_000
#######################################################################################################################################
#                                                           run simulation
#######################################################################################################################################
cnt = 0
for _ ∈ 1:n_sim
    τ = rand(Normal(0, 1))
    n_sub_events1 = rand(DiscreteUniform(1, 5))
    δ = rand(Uniform(0, 2))
    model = ACTRUnpacking(; n_sub_events1, bl, Θ..., τ, δ)
    cnt += simulate_trial(model) < 1 ? 1 : 0
end
cnt / n_sim
