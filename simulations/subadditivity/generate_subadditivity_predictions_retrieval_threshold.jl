#######################################################################################################################################
#                                                           load packages
#######################################################################################################################################
cd(@__DIR__)
using Pkg
Pkg.activate("../..")
using Revise
using ACTRModels
using ACTRMCEModels
using Distributions
using Plots
using ACTRMCEModels: simulate_trial
#######################################################################################################################################
#                                                           setup simulation
#######################################################################################################################################
Θ = (mmp = false, noise = true, s = 0.20, blc = 0.0)
bl = Uniform(-2, 2)
max_sub_events = 5
n_sim = 100_000
#######################################################################################################################################
#                                                           run simulation
#######################################################################################################################################
cnt = 0
for _ ∈ 1:n_sim
    τ = rand(Uniform(-2, 2))
    n_sub_events1 = rand(1:max_sub_events)
    δ = rand(Uniform(0, 2))
    model = ACTRUnpacking(; n_sub_events1, bl, Θ..., τ, δ)
    cnt += simulate_trial(model) > 1 ? 1 : 0
end
cnt / n_sim
